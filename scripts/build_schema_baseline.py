#!/usr/bin/env python3
"""Build the consolidated schema baseline for brand-new databases.

The numbered migration files remain the immutable upgrade ledger. This script
only produces a convenience artifact for an empty database; it must never be
used to rewrite or replace an existing database's migration history.
"""
from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MIGRATIONS = ROOT / "migrations"
OUTPUT = MIGRATIONS / "baseline.sql"


def main() -> None:
    paths = sorted(MIGRATIONS.glob("[0-9][0-9][0-9]_*.sql"))
    if not paths:
        raise SystemExit("No hay migraciones numeradas")
    sections = [
        "-- Generated by scripts/build_schema_baseline.py. Do not edit.",
        "-- Applies only to an empty database; numbered migrations remain the upgrade ledger.",
        "",
    ]
    for path in paths:
        sections.extend((f"-- BEGIN {path.name}", path.read_text(encoding="utf-8").rstrip(), f"-- END {path.name}", ""))
    OUTPUT.write_text("\n".join(sections), encoding="utf-8")
    print(f"Baseline generado: {OUTPUT.relative_to(ROOT)} ({len(paths)} migraciones)")


if __name__ == "__main__":
    main()
